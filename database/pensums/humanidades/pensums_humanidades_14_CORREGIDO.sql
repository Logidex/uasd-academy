INSERT INTO _huma_guard SELECT CASE WHEN COUNT(*)=0 THEN 1 ELSE 0 END FROM (
 SELECT p.codigo_plan,p.total_materias,p.total_creditos,
 COUNT(cm.id_materia) AS materias_db,COALESCE(SUM(m.creditos),0) AS creditos_db
 FROM _huma_planes p
 JOIN carreras c ON c.codigo=p.codigo_carrera_db
 LEFT JOIN carrera_materias cm ON cm.id_carrera=c.id_carrera
 LEFT JOIN materias m ON m.id_materia=cm.id_materia
 GROUP BY p.codigo_plan
 HAVING materias_db<>p.total_materias OR creditos_db<>p.total_creditos
);
RELEASE SAVEPOINT importar_humanidades;

-- VALIDACIÓN FINAL (cada fila: materias PDF = BD y créditos PDF = BD).
SELECT p.codigo_plan,p.nombre,
 p.total_materias AS materias_pdf,COUNT(cm.id_materia) AS materias_db,
 p.total_creditos AS creditos_pdf,COALESCE(SUM(m.creditos),0) AS creditos_db
FROM _huma_planes p
JOIN carreras c ON c.codigo=p.codigo_carrera_db
LEFT JOIN carrera_materias cm ON cm.id_carrera=c.id_carrera
LEFT JOIN materias m ON m.id_materia=cm.id_materia
GROUP BY p.codigo_plan ORDER BY p.codigo_plan;
