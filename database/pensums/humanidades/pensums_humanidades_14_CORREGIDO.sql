DROP TABLE IF EXISTS temp._huma_guard;
CREATE TEMP TABLE _huma_guard(ok INTEGER NOT NULL CHECK(ok=1));
-- Se exigen las 14 carreras existentes, en sus escuelas correctas y Humanidades.
INSERT INTO _huma_guard SELECT CASE WHEN COUNT(*)=14 THEN 1 ELSE 0 END
FROM _huma_planes p
JOIN carreras c ON c.codigo=p.codigo_carrera_db
JOIN escuelas e ON e.id_escuela=c.id_escuela AND e.nombre=p.escuela
JOIN facultades f ON f.id_facultad=e.id_facultad AND f.nombre='Facultad de Humanidades';
-- Los 14 códigos de carrera deben ser distintos.
INSERT INTO _huma_guard SELECT CASE WHEN COUNT(DISTINCT codigo_carrera_db)=14 THEN 1 ELSE 0 END FROM _huma_planes;
-- Ningún código existente de materia puede tener créditos incompatibles.
INSERT INTO _huma_guard SELECT CASE WHEN COUNT(*)=0 THEN 1 ELSE 0 END
FROM _huma_materias r JOIN materias m ON m.codigo=r.codigo WHERE m.creditos<>r.creditos;
-- Ninguna materia compartida en este lote puede tener créditos distintos entre carreras.
INSERT INTO _huma_guard SELECT CASE WHEN COUNT(*)=0 THEN 1 ELSE 0 END FROM (
 SELECT codigo FROM _huma_materias GROUP BY codigo HAVING MIN(creditos)<>MAX(creditos)
);
-- No cambiar el período de una relación previamente registrada.
INSERT INTO _huma_guard SELECT CASE WHEN COUNT(*)=0 THEN 1 ELSE 0 END
FROM _huma_materias r
JOIN _huma_planes p ON p.codigo_plan=r.codigo_plan
JOIN carreras c ON c.codigo=p.codigo_carrera_db
JOIN materias m ON m.codigo=r.codigo
JOIN carrera_materias cm ON cm.id_carrera=c.id_carrera AND cm.id_materia=m.id_materia
WHERE cm.periodo<>r.periodo;
-- Planes ya registrados deben tener los mismos datos de procedencia y totales.
INSERT INTO _huma_guard SELECT CASE WHEN COUNT(*)=0 THEN 1 ELSE 0 END
FROM _huma_planes p JOIN fuentes_pensum s ON s.codigo_plan=p.codigo_plan
WHERE s.codigo_carrera_db<>p.codigo_carrera_db OR s.plan<>p.version
   OR s.total_materias<>p.total_materias OR s.total_creditos<>p.total_creditos;

-- Agregar SOLO materias que no estén registradas.
INSERT OR IGNORE INTO materias(codigo,nombre,creditos)
SELECT codigo,MIN(nombre),MIN(creditos) FROM _huma_materias GROUP BY codigo;
-- Agregar SOLO relaciones nuevas para cada pensum.
INSERT OR IGNORE INTO carrera_materias(id_carrera,id_materia,periodo)
SELECT c.id_carrera,m.id_materia,r.periodo
FROM _huma_materias r
JOIN _huma_planes p ON p.codigo_plan=r.codigo_plan
JOIN carreras c ON c.codigo=p.codigo_carrera_db
JOIN materias m ON m.codigo=r.codigo;
-- Registrar procedencia del PDF y versión del plan, sin duplicar registros.
INSERT OR IGNORE INTO fuentes_pensum
 (codigo_plan,codigo_carrera_db,plan,pdf_fuente,total_materias,total_creditos)
SELECT codigo_plan,codigo_carrera_db,version,pdf,total_materias,total_creditos
FROM _huma_planes;

