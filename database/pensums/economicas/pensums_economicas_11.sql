JOIN _economicas_planes p ON p.codigo_plan=r.plan
JOIN carreras c ON c.codigo='PLAN-' || p.codigo_plan
JOIN materias m ON m.codigo=r.codigo;
INSERT OR IGNORE INTO fuentes_pensum(codigo_plan,codigo_carrera_db,plan,pdf_fuente,total_materias,total_creditos)
SELECT p.codigo_plan,c.codigo,p.version,p.pdf,p.total_materias,p.total_creditos
FROM _economicas_planes p JOIN carreras c ON c.codigo='PLAN-'||p.codigo_plan;
COMMIT;
-- VERIFICACIÓN: encontrar pensums con menos filas que las declaradas o créditos distintos por colisiones históricas.
SELECT p.codigo_plan,p.nombre,p.total_materias AS materias_pdf,p.total_creditos AS creditos_pdf,
 COUNT(cm.id_materia) AS materias_db,COALESCE(SUM(m.creditos),0) AS creditos_db
 FROM _economicas_planes p LEFT JOIN carreras c ON c.codigo='PLAN-'||p.codigo_plan
 LEFT JOIN carrera_materias cm ON cm.id_carrera=c.id_carrera
 LEFT JOIN materias m ON m.id_materia=cm.id_materia
 GROUP BY p.codigo_plan ORDER BY p.codigo_plan;
-- Revisa diferencias de crédito entre los PDFs y el catálogo maestro existente:
SELECT r.plan,r.codigo,MIN(r.nombre) AS nombre_pdf,MIN(r.creditos) AS creditos_pdf,m.nombre AS nombre_catalogo,m.creditos AS creditos_catalogo FROM _economicas_materias r JOIN materias m ON m.codigo=r.codigo WHERE r.creditos<>m.creditos GROUP BY r.plan,r.codigo ORDER BY r.plan,r.codigo;
