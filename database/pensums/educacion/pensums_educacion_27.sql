-- Validaciones ANTES de tocar las tablas definitivas.
DROP TABLE IF EXISTS temp._edu_guard;
CREATE TEMP TABLE _edu_guard(ok INTEGER NOT NULL CHECK(ok=1));
-- Los 27 PDF apuntan a escuelas que existen en la Facultad de Ciencias de la Educacion.
INSERT INTO _edu_guard SELECT CASE WHEN COUNT(*)=27 THEN 1 ELSE 0 END
FROM _edu_planes p
JOIN escuelas e ON e.nombre=p.escuela
JOIN facultades f ON f.id_facultad=e.id_facultad
 AND f.nombre='Facultad de Ciencias de la Educación';
-- Códigos distintos y solo cuatro nuevos (respecto al catálogo previo).
INSERT INTO _edu_guard SELECT CASE WHEN COUNT(DISTINCT codigo_carrera_db)=27 THEN 1 ELSE 0 END
FROM _edu_planes;
INSERT INTO _edu_guard SELECT CASE WHEN COUNT(*)=4 THEN 1 ELSE 0 END FROM _edu_planes WHERE crear_carrera=1;
-- Cualquier carrera previa debe estar en la escuela correcta y misma facultad.
INSERT INTO _edu_guard SELECT CASE WHEN COUNT(*)=0 THEN 1 ELSE 0 END
FROM _edu_planes p
JOIN carreras c ON c.codigo=p.codigo_carrera_db
JOIN escuelas e ON e.id_escuela=c.id_escuela
JOIN facultades f ON f.id_facultad=e.id_facultad
WHERE e.nombre<>p.escuela OR f.nombre<>'Facultad de Ciencias de la Educación';
-- Evitar créditos distintos para un mismo codigo de materia (en BD y en el lote).
INSERT INTO _edu_guard SELECT CASE WHEN COUNT(*)=0 THEN 1 ELSE 0 END
FROM _edu_materias r JOIN materias m ON m.codigo=r.codigo WHERE m.creditos<>r.creditos;
INSERT INTO _edu_guard SELECT CASE WHEN COUNT(*)=0 THEN 1 ELSE 0 END FROM (
 SELECT codigo FROM _edu_materias GROUP BY codigo HAVING MIN(creditos)<>MAX(creditos)
);
-- Si una relacion existía, su semestre no debe cambiar silenciosamente.
INSERT INTO _edu_guard SELECT CASE WHEN COUNT(*)=0 THEN 1 ELSE 0 END
FROM _edu_materias r
JOIN _edu_planes p ON p.codigo_plan=r.codigo_plan
JOIN carreras c ON c.codigo=p.codigo_carrera_db
JOIN materias m ON m.codigo=r.codigo
JOIN carrera_materias cm ON cm.id_carrera=c.id_carrera AND cm.id_materia=m.id_materia
WHERE cm.periodo<>r.periodo;
-- Si un plan se importó antes, su procedencia, versión y totales deben coincidir.
INSERT INTO _edu_guard SELECT CASE WHEN COUNT(*)=0 THEN 1 ELSE 0 END
FROM _edu_planes p JOIN fuentes_pensum s ON s.codigo_plan=p.codigo_plan
WHERE s.codigo_carrera_db<>p.codigo_carrera_db OR s.plan<>p.version
 OR s.total_materias<>p.total_materias OR s.total_creditos<>p.total_creditos;

-- Crear solo las cuatro carreras faltantes, con sus escuelas correctas.
INSERT OR IGNORE INTO carreras(codigo,nombre,id_escuela,descripcion)
SELECT p.codigo_carrera_db,p.nombre_db,e.id_escuela,
 'Importado de pensum UASD, programa '||p.codigo_plan||', plan '||p.version
FROM _edu_planes p
JOIN escuelas e ON e.nombre=p.escuela
JOIN facultades f ON f.id_facultad=e.id_facultad
 AND f.nombre='Facultad de Ciencias de la Educación'
WHERE p.crear_carrera=1
AND NOT EXISTS (SELECT 1 FROM carreras c WHERE c.codigo=p.codigo_carrera_db);
-- Todos los programas (27) deben existir con su escuela correcta.
INSERT INTO _edu_guard SELECT CASE WHEN COUNT(*)=27 THEN 1 ELSE 0 END
FROM _edu_planes p
JOIN carreras c ON c.codigo=p.codigo_carrera_db
JOIN escuelas e ON e.id_escuela=c.id_escuela AND e.nombre=p.escuela
JOIN facultades f ON f.id_facultad=e.id_facultad
 AND f.nombre='Facultad de Ciencias de la Educación';
-- Materias compartidas: insertarlas solo si faltan.
INSERT OR IGNORE INTO materias(codigo,nombre,creditos)
SELECT codigo,MIN(nombre),MIN(creditos) FROM _edu_materias GROUP BY codigo;
INSERT OR IGNORE INTO carrera_materias(id_carrera,id_materia,periodo)
SELECT c.id_carrera,m.id_materia,r.periodo
FROM _edu_materias r
JOIN _edu_planes p ON p.codigo_plan=r.codigo_plan
JOIN carreras c ON c.codigo=p.codigo_carrera_db
JOIN materias m ON m.codigo=r.codigo;
INSERT OR IGNORE INTO fuentes_pensum
 (codigo_plan,codigo_carrera_db,plan,pdf_fuente,total_materias,total_creditos)
SELECT codigo_plan,codigo_carrera_db,version,pdf,total_materias,total_creditos
FROM _edu_planes;

-- Validacion final: cada programa debe coincidir exactamente con el PDF en cantidad y creditos.
INSERT INTO _edu_guard SELECT CASE WHEN COUNT(*)=0 THEN 1 ELSE 0 END FROM (
 SELECT p.codigo_plan,p.total_materias,p.total_creditos,
 COUNT(cm.id_materia) AS materias_db,COALESCE(SUM(m.creditos),0) AS creditos_db
 FROM _edu_planes p
 JOIN carreras c ON c.codigo=p.codigo_carrera_db
 LEFT JOIN carrera_materias cm ON cm.id_carrera=c.id_carrera
 LEFT JOIN materias m ON m.id_materia=cm.id_materia
 GROUP BY p.codigo_plan
 HAVING materias_db<>p.total_materias OR creditos_db<>p.total_creditos
);
RELEASE SAVEPOINT importar_educacion;

