 p.total_materias AS materias_pdf,COUNT(cm.id_materia) AS materias_db,
 p.total_creditos AS creditos_pdf,COALESCE(SUM(m.creditos),0) AS creditos_db
FROM _edu_planes p
JOIN carreras c ON c.codigo=p.codigo_carrera_db
LEFT JOIN carrera_materias cm ON cm.id_carrera=c.id_carrera
LEFT JOIN materias m ON m.id_materia=cm.id_materia
GROUP BY p.codigo_plan ORDER BY p.codigo_plan;
