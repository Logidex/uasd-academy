SELECT p.codigo_plan,p.nombre,p.total_materias,p.total_creditos,
       COUNT(cm.id_materia) AS materias_guardadas,
       COALESCE(SUM(m.creditos),0) AS creditos_catalogo
FROM _ciencias_planes p LEFT JOIN carreras c ON c.id_carrera=COALESCE((SELECT c2.id_carrera FROM carreras c2 WHERE c2.codigo='PLAN-'||p.codigo_plan LIMIT 1),(SELECT c2.id_carrera FROM carreras c2 WHERE c2.nombre=p.nombre LIMIT 1))
LEFT JOIN carrera_materias cm ON cm.id_carrera=c.id_carrera
LEFT JOIN materias m ON m.id_materia=cm.id_materia
GROUP BY p.codigo_plan ORDER BY p.codigo_plan;
