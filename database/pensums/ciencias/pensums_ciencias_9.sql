-- Diagnósticos previos: códigos existentes con nombre o créditos diferentes.
SELECT 'CONFLICTO_MATERIA' AS tipo,r.codigo, m.nombre AS nombre_existente, r.nombre AS nombre_pdf, m.creditos AS creditos_existentes, r.creditos AS creditos_pdf
FROM _ciencias_filas r JOIN materias m ON m.codigo=r.codigo
WHERE lower(trim(m.nombre)) <> lower(trim(r.nombre)) OR m.creditos <> r.creditos
GROUP BY r.codigo,m.nombre,r.nombre,m.creditos,r.creditos;

-- Se conservan los registros existentes, y se insertan los nuevos por código.
INSERT OR IGNORE INTO materias(codigo,nombre,creditos)
SELECT codigo,nombre,creditos FROM _ciencias_filas GROUP BY codigo ORDER BY plan,codigo;

-- Cada plan se enlaza por código de catálogo o, como alternativa, nombre exacto.
INSERT OR IGNORE INTO carrera_materias(id_carrera,id_materia,periodo)
SELECT COALESCE((SELECT c.id_carrera FROM carreras c WHERE c.codigo='PLAN-' || r.plan LIMIT 1), (SELECT c.id_carrera FROM carreras c WHERE c.nombre=p.nombre LIMIT 1)),
       m.id_materia,r.periodo
FROM _ciencias_filas r JOIN _ciencias_planes p ON p.codigo_plan=r.plan
