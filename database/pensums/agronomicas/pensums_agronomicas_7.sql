INSERT INTO _agro_validacion
SELECT CASE WHEN COUNT(*)=7 THEN 1 ELSE 0 END
FROM _agro_planes p
JOIN carreras c ON c.codigo='PLAN-' || p.codigo_plan
JOIN escuelas e ON e.id_escuela=c.id_escuela AND e.nombre=p.escuela
JOIN facultades f ON f.id_facultad=e.id_facultad
 AND f.nombre='Facultad de Ciencias Agronómicas y Veterinarias';
-- Evitar insertar sobre un código ya existente con créditos contradictorios.
INSERT INTO _agro_validacion
SELECT CASE WHEN COUNT(*)=0 THEN 1 ELSE 0 END
FROM _agro_materias r JOIN materias m ON m.codigo=r.codigo WHERE m.creditos<>r.creditos;
-- Asegurarse de que no existan códigos con diferentes créditos dentro del lote.
INSERT INTO _agro_validacion
SELECT CASE WHEN COUNT(*)=0 THEN 1 ELSE 0 END
FROM (SELECT codigo FROM _agro_materias GROUP BY codigo HAVING MIN(creditos)<>MAX(creditos));
-- Insertar materias faltantes sin sobrescribir las que ya existen.
INSERT OR IGNORE INTO materias(codigo,nombre,creditos)
SELECT codigo,MIN(nombre),MIN(creditos) FROM _agro_materias GROUP BY codigo;
-- Relacionar carrera con sus materias; claves duplicadas son ignoradas.
INSERT OR IGNORE INTO carrera_materias(id_carrera,id_materia,periodo)
SELECT c.id_carrera, m.id_materia, r.periodo
FROM _agro_materias r
JOIN carreras c ON c.codigo='PLAN-'||r.plan
JOIN materias m ON m.codigo=r.codigo;
INSERT OR IGNORE INTO fuentes_pensum
(codigo_plan,codigo_carrera_db,plan,pdf_fuente,total_materias,total_creditos)
SELECT p.codigo_plan,c.codigo,p.version,p.pdf,p.total_materias,p.total_creditos
FROM _agro_planes p JOIN carreras c ON c.codigo='PLAN-'||p.codigo_plan;
COMMIT;

