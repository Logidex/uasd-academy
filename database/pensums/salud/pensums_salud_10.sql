DROP TABLE IF EXISTS temp._salud_guard;
CREATE TEMP TABLE _salud_guard (ok INTEGER NOT NULL CHECK (ok=1));
-- Los 10 programas deben estar en la facultad, y sus escuelas deben existir.
INSERT INTO _salud_guard SELECT CASE WHEN COUNT(*)=10 THEN 1 ELSE 0 END
FROM _salud_planes p JOIN escuelas e ON e.nombre=p.escuela
JOIN facultades f ON f.id_facultad=e.id_facultad
 AND f.nombre='Facultad de Ciencias de la Salud';
-- No sobrescribir códigos de programa ya existentes asignados a otra escuela.
INSERT INTO _salud_guard SELECT CASE WHEN COUNT(*)=0 THEN 1 ELSE 0 END
FROM _salud_planes p JOIN carreras c ON c.codigo='PLAN-'||p.codigo_plan
JOIN escuelas e ON e.id_escuela=c.id_escuela
JOIN facultades f ON f.id_facultad=e.id_facultad
WHERE e.nombre<>p.escuela OR f.nombre<>'Facultad de Ciencias de la Salud';
-- No importar más/menos créditos en cursos previamente cargados.
INSERT INTO _salud_guard SELECT CASE WHEN COUNT(*)=0 THEN 1 ELSE 0 END
FROM _salud_materias r JOIN materias m ON m.codigo=r.codigo
WHERE m.creditos<>r.creditos;
-- Un mismo código del lote no debe tener créditos contradictorios.
INSERT INTO _salud_guard SELECT CASE WHEN COUNT(*)=0 THEN 1 ELSE 0 END
FROM (SELECT codigo FROM _salud_materias GROUP BY codigo
 HAVING MIN(creditos)<>MAX(creditos));
-- Mismo curso en el mismo programa no debe tener periodo diferente en datos anteriores.
INSERT INTO _salud_guard SELECT CASE WHEN COUNT(*)=0 THEN 1 ELSE 0 END
FROM _salud_materias r
JOIN carreras c ON c.codigo='PLAN-'||r.plan
JOIN materias m ON m.codigo=r.codigo
JOIN carrera_materias cm ON cm.id_carrera=c.id_carrera AND cm.id_materia=m.id_materia
WHERE cm.periodo<>r.periodo;
-- Solo las dos carreras ausentes: no cambiar ninguna carrera anterior.
INSERT INTO carreras(codigo,nombre,id_escuela,descripcion)
SELECT 'PLAN-P-ENF1','Licenciatura en Enfermería (plan 000012)',e.id_escuela,
       'Programa del plan 000012, distinto de P-ENFE (plan 000013)'
FROM escuelas e JOIN facultades f ON f.id_facultad=e.id_facultad
WHERE e.nombre='Escuela de Enfermería' AND f.nombre='Facultad de Ciencias de la Salud'
AND NOT EXISTS(SELECT 1 FROM carreras WHERE codigo='PLAN-P-ENF1');
INSERT INTO carreras(codigo,nombre,id_escuela,descripcion)
SELECT 'PLAN-P-PMED','Pre-Médica (Medicina)',e.id_escuela,
       'Programa de Pre-Médica, plan 000014'
FROM escuelas e JOIN facultades f ON f.id_facultad=e.id_facultad
WHERE e.nombre='Escuela de Medicina' AND f.nombre='Facultad de Ciencias de la Salud'
AND NOT EXISTS(SELECT 1 FROM carreras WHERE codigo='PLAN-P-PMED');
-- Los 10 programas deben existir correctamente después de las inserciones condicionales.
INSERT INTO _salud_guard SELECT CASE WHEN COUNT(*)=10 THEN 1 ELSE 0 END
FROM _salud_planes p JOIN carreras c ON c.codigo='PLAN-'||p.codigo_plan
JOIN escuelas e ON e.id_escuela=c.id_escuela AND e.nombre=p.escuela
JOIN facultades f ON f.id_facultad=e.id_facultad
 AND f.nombre='Facultad de Ciencias de la Salud';
-- Insertar solo materias nuevas, sin alterar el catálogo anterior.
INSERT OR IGNORE INTO materias(codigo,nombre,creditos)
SELECT codigo,MIN(nombre),MIN(creditos) FROM _salud_materias GROUP BY codigo;
-- Asociar las materias al programa adecuado.
INSERT OR IGNORE INTO carrera_materias(id_carrera,id_materia,periodo)
SELECT c.id_carrera,m.id_materia,r.periodo
FROM _salud_materias r
JOIN carreras c ON c.codigo='PLAN-'||r.plan
JOIN materias m ON m.codigo=r.codigo;
-- Guardar procedencia.
INSERT OR IGNORE INTO fuentes_pensum
(codigo_plan,codigo_carrera_db,plan,pdf_fuente,total_materias,total_creditos)
SELECT p.codigo_plan,c.codigo,p.version,p.pdf,p.total_materias,p.total_creditos
FROM _salud_planes p JOIN carreras c ON c.codigo='PLAN-'||p.codigo_plan;

-- Comprobar ANTES de finalizar que el resultado coincide con el PDF en los 10 programas.
INSERT INTO _salud_guard SELECT CASE WHEN COUNT(*)=0 THEN 1 ELSE 0 END
FROM (
 SELECT p.codigo_plan,p.total_materias,p.total_creditos,
        COUNT(cm.id_materia) total_db,COALESCE(SUM(m.creditos),0) creditos_db
 FROM _salud_planes p
 JOIN carreras c ON c.codigo='PLAN-'||p.codigo_plan
 LEFT JOIN carrera_materias cm ON cm.id_carrera=c.id_carrera
 LEFT JOIN materias m ON m.id_materia=cm.id_materia
 GROUP BY p.codigo_plan
 HAVING total_db<>p.total_materias OR creditos_db<>p.total_creditos
);
COMMIT;

-- VALIDACIÓN FINAL: deben coincidir las columnas PDF y BD para los 10 planes.
SELECT p.codigo_plan,p.nombre,p.total_materias AS materias_pdf,
 p.total_creditos AS creditos_pdf,COUNT(cm.id_materia) AS materias_db,
 COALESCE(SUM(m.creditos),0) AS creditos_db
FROM _salud_planes p
JOIN carreras c ON c.codigo='PLAN-'||p.codigo_plan
LEFT JOIN carrera_materias cm ON cm.id_carrera=c.id_carrera
LEFT JOIN materias m ON m.id_materia=cm.id_materia
GROUP BY p.codigo_plan ORDER BY p.codigo_plan;
SELECT (SELECT COUNT(*) FROM materias) AS materias_unicas,
       (SELECT COUNT(*) FROM carrera_materias) AS relaciones,
       (SELECT COUNT(*) FROM fuentes_pensum) AS planes_registrados;
